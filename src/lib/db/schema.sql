-- Automatically create public.users row on signup
create or replace function public.handle_new_user()
returns trigger 
language plpgsql 
security definer
set search_path = public
as $$
declare
  new_household_id uuid;
begin
  -- Create a new household for the user
  insert into public.households (name) 
  values (split_part(new.email, '@', 1) || '''s Household')
  returning id into new_household_id;

  -- Create user linked to household
  insert into public.users (id, display_name, avatar_url, metabolic_state_json, taste_profile_json, streak_count, calorie_target, household_id)
  values (
    new.id,
    split_part(new.email, '@', 1),
    null,
    '{"current_goal":"maintenance"}',
    '{"sweet": 0.5, "bitter": 0.5, "sour": 0.5, "umami": 0.5, "confidence": 0}',
    0,
    2000,
    new_household_id
  );
  return new;
end;
$$;

